"""Source of patches/hpd-skip-unused.json. Run in an unpacked work dir (RT=runtime_0x200000.bin).

The hot-plug level commands (mailbox 0x20 sub 3) are no longer sent for the
two port-table entries without a connector (ports 4 and 5, front-end id 0).

Port table 0x3B4950 has 6 entries; ports 0-3 are USB-C, DP, HDMI 1, HDMI 2
(front-end ids 7, 8, 0x0B, 0x0C). Ports 4 and 5 are HDMI-class entries of the
reference design (codes 4 and 2 in 0x3B427B) with front-end id 0 in 0x3B4281:
there is no connector behind them, and nothing selects them - the menu input
(+0x4F 1-4 -> ports 0-3, sub_2678D9), the second picture of split screen /
PIP (+0xB2 0-3 -> ports 0-3), the automatic scan (0 -> 1 -> 2 -> 3 -> 0,
sub_2653EA) and DDC/CI use ports 0-3 only. Split screen is not affected.
sub_2394DC (main loop, after every hot-plug level change) sends 0x20 sub 3
(id, level) for each pending port; at start-up all six are pending, and the
front-end needs 70-230 ms per command while it is busy right after the port
enable (docs/firmware-map.md section 27), so the two id-0 commands keep the
main loop waiting ~0.2 s at every start.

Patch: the jal 0x2394AF (0x20 sub 3 wrapper) at 0x23954A goes through a stub
that returns without sending when the id (r3) is 0.
"""
import sys, json, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'aeon'))
import aeondis as A, aeonasm as S

d = open(os.environ.get('RT', 'runtime_0x200000.bin'), 'rb').read()
def cur(a, n): return d[a - 0x200000:a - 0x200000 + n]

SITE, WRAP = 0x23954A, 0x2394AF
CAVE = 0x2039D0                      # linker padding after nosignal-once (0x2039B0-0x2039C9), before 0x203A00
assert A.decode(d, SITE - 0x200000, SITE)['target'] == WRAP
assert A.decode(d, 0x239544 - 0x200000, 0x239544)['ops'] == 'r3,0x0(r6)'     # r3 = id from 0x3B4281[i]
assert cur(0x3B4281, 6).hex() == '07080b0c0000'
assert A.decode(d, WRAP + 0xB - 0x200000, WRAP + 0xB)['ops'] == 'r3,r0,0x20'  # 0x20 ...
prog = [
 'hsu:',
 ('bg.beqi', {'A': 3, 'I': 0, ';': 'hsu_skip'}),
 ('bg.j', {'/': WRAP}),
 'hsu_skip:',
 ('bt.movi', {'D': 3, 'I': 1}), ('bt.jr', {'A': 9}),
]
code, L = S.assemble(prog, CAVE)
assert CAVE + len(code) <= 0x203A00 and cur(CAVE, len(code)) == b'\0' * len(code)
for a, b, x in A.disasm(code, CAVE, CAVE + len(code), CAVE):
    print('%08x: %-12s %-9s %s' % (a, b.hex(' '), x['mnem'], x['ops']))
hook = S.encode('bg.jal', {'/': CAVE}, SITE)
print('%06x: %s -> %s' % (SITE, cur(SITE, 4).hex(), hook.hex()))
patch = {
 'name': 'hpd-skip-unused',
 'summary': 'No hot-plug level commands (0x20 sub 3) for the two port-table entries without a connector (ports 4/5, id 0); saves ~0.2 s of main-loop waiting at every start',
 'status': 'untested',
 'edits': [
  {'addr': '0x%06X' % CAVE, 'old': '00' * len(code), 'new': code.hex(),
   'asm': 'hsu (linker padding 0x2039D0): id 0 -> return, else j 0x2394AF'},
  {'addr': '0x%06X' % SITE, 'old': cur(SITE, 4).hex(), 'new': hook.hex(),
   'asm': 'sub_2394DC: jal 0x2394AF (0x20 sub 3) -> jal hsu'},
 ],
 'notes': 'See the docstring of tools/patches_src_hpd_skip_unused.py. Generated by tools/patches_src_hpd_skip_unused.py.',
}
out = os.environ.get('OUT', 'hpd-skip-unused.json')
json.dump(patch, open(out, 'w'), indent=2)
open(out, 'a').write('\n')
