#!/usr/bin/env python3
"""Source of patches/port-nosignal.json. Run in an unpacked work dir (RT=runtime_0x200000.bin).

Shorter "no signal" decision per input port, for a faster automatic input
scan and a faster "No signal" message.

Vendor (sub_260E0E -> sub_23E5C5, port +0x1A; see port-accept for +0x18):
the port monitor sub_23B068 (every 20 ms per port) declares a port without
signal after +0x1A passes (port state 2, flags +0x1C |= 6):
- type 0x20 (ports 0 and 1): 400 passes = 8 s (200 when settings +0x48 bit 2
  or flg bit 0 is set);
- type bit 3/4/0x400 (ports 2-5): 500 passes = 10 s (200 with the flag);
- types bit 0 and bit 1/2 (20 / 60 passes) do not occur in the port table.
With "Select Automatically" the scan waits this long on every port before the
next one: 3-4 ports took 30 s+ to "No signal" (owner's report 2026-10-07,
fixed input quicker). LG 28MQ780 (same SDK) uses 100 passes (2 s) for both
classes.

Patch: the four no-signal values (500, 400 and the two 200 flag variants)
become NOSIG passes (env NOSIG, default 200 = 4 s, the vendor's own value for
the flag case). Not lower by default: on a power-key start the source's
signal arrived ~2 s after the port started searching (log 2026-10-06), so
LG's 2 s could declare "no signal" (and move an automatic scan on) before the
source is ready. The accept thresholds are unchanged.
"""
import sys, json, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'aeon'))
import aeondis as A, aeonasm as S

d = open(os.environ.get('RT', 'runtime_0x200000.bin'), 'rb').read()
def cur(a, n): return d[a - 0x200000:a - 0x200000 + n]

NOSIG = int(os.environ.get('NOSIG', '200'))
assert 50 <= NOSIG <= 255
SITES = [  # addr, stock bytes, register, vendor value, what
 (0x260E70, '50e0c8', 7, 200, 'type bit3/4/0x400, flag case (cmov source)'),
 (0x260E73, 'c8a001f4', 5, 500, 'type bit3/4/0x400, normal case'),
 (0x260ED1, '50a0c8', 5, 200, 'type 0x20, flag case'),
 (0x260EDA, 'c8a00190', 5, 400, 'type 0x20, normal case'),
]
edits = []
for a, old, reg, val, what in SITES:
    ob = cur(a, len(old) // 2)
    assert ob.hex() == old, (hex(a), ob.hex())
    x = A.decode(ob, 0, a)
    assert x['mnem'] == 'b.ori' and x['ops'] == 'r%d,r0,%#x' % (reg, val), x
    nb = (S.encode('bn.ori', {'D': reg, 'A': 0, 'N': NOSIG}, a) if len(ob) == 3 else
          S.encode('bg.ori', {'D': reg, 'A': 0, 't': NOSIG}, a))
    assert len(nb) == len(ob) and A.decode(nb, 0, a)['ops'] == 'r%d,r0,%#x' % (reg, NOSIG)
    print('%06x: %s -> %s  %s %d -> %d passes' % (a, ob.hex(), nb.hex(), what, val, NOSIG))
    if nb != ob:
        edits.append({'addr': '0x%06X' % a, 'old': ob.hex(), 'new': nb.hex(),
                      'asm': 'sub_260E0E ori r%d,r0,%#x -> ori r%d,r0,%#x (port +0x1A no-signal threshold, %s)' % (reg, val, reg, NOSIG, what)})
patch = {
 'name': 'port-nosignal',
 'summary': 'Declare an input port "no signal" after %d x 20 ms = %.1f s instead of 8-10 s (faster automatic input scan and "No signal")' % (NOSIG, NOSIG * 0.02),
 'status': 'untested',
 'edits': edits,
 'notes': ("Port +0x1A thresholds set by sub_260E0E (vendor: 400 passes for type 0x20, 500 for types bit3/4/0x400, "
           "200 in the flag case). LG 28MQ780 uses 100. Accept thresholds (+0x18, see port-accept) unchanged. "
           "Generated by tools/patches_src_port_nosignal.py (NOSIG=n, 50-255)."),
}
out = os.environ.get('OUT', 'port-nosignal.json')
json.dump(patch, open(out, 'w'), indent=2)
open(out, 'a').write('\n')
