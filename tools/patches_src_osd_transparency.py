#!/usr/bin/env python3
"""Source of patches/osd-transparency.json. Run in an unpacked work dir (RT=runtime_0x200000.bin).

Finer OSD transparency steps: 11 levels 0-10 instead of 6 levels 0-5, over
the same range.

Vendor (OSD page, item "Transparency", settings +0x79):
- adjust 0x2660AB: sub_263D3C(value, 0, 5, 1) (minimum 0, maximum 5, step 1);
- apply sub_25C26E(level): alpha = 0x3F - 8 x level (63 solid, 55, 47, 39,
  31, 23), written to OSD windows 1-3 with sub_23C00F(window, 2, alpha);
- settings load 0x2631F0: level = level mod 6;
- default level 1 (alpha 55) at the settings reset (0x262390) and the factory
  reset (0x26A142).
The value is shown as a plain number (getter 0x2652F9), so 0-10 display
correctly.

Patch: maximum 10, alpha = 0x3F - 4 x level (63, 59, 55, ... 23), load check
mod 11, defaults 2 (alpha 55, as before). A level stored by the vendor
firmware keeps its number, i.e. half its former transparency step (old 1 =
alpha 55 becomes 59); set it again once in the menu if needed.
"""
import sys, json, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'aeon'))
import aeondis as A, aeonasm as S

d = open(os.environ.get('RT', 'runtime_0x200000.bin'), 'rb').read()
def cur(a, n): return d[a - 0x200000:a - 0x200000 + n]

LEVELS = 11
edits_spec = [
 (0x2660C3, '98c5', '98ca', 'adjust 0x2660AB: sub_263D3C maximum 5 -> 10 (movi r6)'),
 (0x25C276, '4c6318', '4c6310', 'apply sub_25C26E: alpha = 0x3F - (level << 3) -> 0x3F - (level << 2)'),
 (0x2631F3, '98a6', '98ab', 'settings load: level mod 6 -> mod 11 (movi r5)'),
 (0x262390, '9b21', '9b22', 'settings reset: default level 1 -> 2 (alpha 55 as before; movi r25)'),
 (0x26A142, '99a1', '99a2', 'factory reset: default level 1 -> 2 (alpha 55 as before; movi r13)'),
]
for a, old, new, txt in edits_spec:
    assert cur(a, len(old) // 2).hex() == old, (hex(a), cur(a, len(old) // 2).hex())
    x = A.decode(bytes.fromhex(new) + b'\0\0', 0, a)
    print('%06x: %s -> %s  %s %s' % (a, old, new, x['mnem'], x['ops']))
assert cur(0x2660BE, 3).hex() == '108779' and cur(0x2660C7, 4).hex() == 'e7ffb8ea'   # lbz r4,0x79 ; jal sub_263D3C
assert cur(0x2631F0, 3).hex() == '10f779' and cur(0x2631F5, 3).hex() == '40c729'     # lbz r7,0x79 ; divu
assert cur(0x26245B, 3).hex() == '1b2779' and cur(0x26A144, 3).hex() == '19a779'     # sb 0x79 (r25 / r13)
assert cur(0x25C279, 6).hex() == '51403f41 4a1d'.replace(' ', '')                  # ori r10,r0,0x3f ; sub
alpha = [0x3F - 4 * k for k in range(LEVELS)]
assert alpha[-1] == 0x3F - 8 * 5 and alpha[2] == 0x3F - 8 * 1
patch = {
 'name': 'osd-transparency',
 'summary': 'OSD transparency in 11 levels (0-10, alpha 63-23 in steps of 4) instead of 6 (steps of 8); same range',
 'status': 'untested (emulator-checked display of 0-10)',
 'edits': [{'addr': '0x%06X' % a, 'old': old, 'new': new, 'asm': txt} for a, old, new, txt in edits_spec],
 'notes': 'See the docstring of tools/patches_src_osd_transparency.py. Generated by tools/patches_src_osd_transparency.py.',
}
out = os.environ.get('OUT', 'osd-transparency.json')
json.dump(patch, open(out, 'w'), indent=2)
open(out, 'a').write('\n')
