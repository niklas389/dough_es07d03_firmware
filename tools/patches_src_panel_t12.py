"""Source of patches/panel-t12.json. Run in an unpacked work dir (RT=runtime_0x200000.bin).

LM270WR8 spec 3-6, T12: VLCD must stay off >= 1000 ms before it is applied again.
The vendor panel-off (sub_245860) already arms a 1200 ms countdown (0x4551B6,
flag off=0x4551A7, decremented by the 1 ms ISR, which clears off at 0), but no
panel-on path checks it. This patch keeps the vendor timer and waits at panel-on
until off is clear, in 1 ms steps and at most 1200 steps, so the main loop is
only held when the panel is re-powered too early.
"""
import sys, json, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'aeon'))
import aeondis as A, aeonasm as S

d = open(os.environ.get('RT', 'runtime_0x200000.bin'), 'rb').read()
def cur(a, n): return d[a - 0x200000:a - 0x200000 + n]

CAVE = 0x203900          # linker padding 0x203800-0x203FFF; standby-lhs uses 0x203800-0x203888
SUB_23CCD5 = 0x23ccd5    # panel output mode (first step of both panel-on routines)
SUB_241505 = 0x241505    # busy-wait r3 ms on the 1 ms ISR counter
R1, R3, R7, R9, R10 = 1, 3, 7, 9, 10

prog = [
 'wait_t12:',            # replaces jal sub_23CCD5 (r3 = 2) at the start of panel-on
 ('bt.addi', {'D': R1, 'I': -8}),
 ('bn.sw', {':': 4, 'A': R1, 'B': R9}),
 ('bn.sw', {':': 0, 'A': R1, 'B': R10}),
 ('bg.ori', {'D': R10, 'A': 0, 't': 1200}),        # upper bound in ms
 'loop:',
 ('bg.movhi', {'D': R7, 'U': 0x45}),
 ('bg.lbz', {'?': R7, 'A': R7, '!': 0x51a7}),       # off: T12 still running
 ('bg.beqi', {'A': R7, 'I': 0, ';': 'done'}),
 ('bt.movi', {'D': R3, 'I': 1}),
 ('bg.jal', {'/': SUB_241505}),
 ('bt.addi', {'D': R10, 'I': -1}),
 ('bg.bnei', {'A': R10, 'I': 0, ';': 'loop'}),
 'done:',
 ('bn.lwz', {'D': R10, 'A': R1, ':': 0}),
 ('bn.lwz', {'D': R9, 'A': R1, ':': 4}),
 ('bt.addi', {'D': R1, 'I': 8}),
 ('bt.movi', {'D': R3, 'I': 2}),
 ('bg.j', {'/': SUB_23CCD5}),                       # tail call, returns to the hook site
]
code, L = S.assemble(prog, CAVE)
print('cave bytes', len(code))
for a, b, x in A.disasm(code, CAVE, CAVE + len(code), CAVE):
    lab = [k for k, v in L.items() if v == a]
    print(('%-10s' % (lab[0] + ':' if lab else '')) + '%08x: %-12s %-9s %s' % (a, b.hex(' '), x['mnem'], x['ops']))
assert cur(CAVE, len(code)) == b'\0' * len(code)

hooks = [
 (0x245938, 'full panel-on sub_245919'),
 (0x245802, 'panel-on without link sub_2457FB (stock pre-standby cancel)'),
]
edits = [{'addr': '0x%06X' % CAVE, 'old': '00' * len(code), 'new': code.hex(),
          'asm': 'T12 wait in linker padding (0x203900)'}]
for a, c in hooks:
    ob = cur(a, 4)
    x = A.decode(ob, 0, a)
    assert x['name'] == 'bg.jal' and x['target'] == SUB_23CCD5, (hex(a), x)
    assert cur(a - 2, 2) == bytes.fromhex('9862')     # b.movi r3,0x2 just before
    nb = S.encode('bg.jal', {'/': L['wait_t12']}, a)
    y = A.decode(nb, 0, a)
    print('%x  %s %-14s -> %s %s   ; %s' % (a, ob.hex(), x['ops'], nb.hex(), y['ops'], c))
    edits.append({'addr': '0x%06X' % a, 'old': ob.hex(), 'new': nb.hex(),
                  'asm': 'b.jal sub_23ccd5 -> b.jal wait_t12 (%s)' % c})

patch = {
 'name': 'panel-t12',
 'summary': "Enforce the panel datasheet's T12 (VLCD off >= 1 s before it may return): panel-on waits for the vendor's own 1.2 s off-timer",
 'status': 'analysis-verified, hardware test pending',
 'edits': edits,
 'notes': ("sub_245860 (panel off) arms a 1200 ms countdown (0x4551B6, flag off=0x4551A7) that the 1 ms ISR "
           "(sub_240C55) decrements, clearing off at 0; no panel-on path checked it, so VLCD could be re-applied "
           "< 1 s after removal (LM270WR8 spec 3-6, T12 >= 1000 ms). Both panel-on routines now wait for off == 0 "
           "before powering the panel (1 ms steps, at most 1200 steps, so a stalled timer cannot hang the loop). "
           "Nothing waits when the panel was off long enough. Generated by tools/patches_src_panel_t12.py."),
}
json.dump(patch, open(os.environ.get('OUT', 'panel-t12.json'), 'w'), indent=2)
open(os.environ.get('OUT', 'panel-t12.json'), 'a').write('\n')
