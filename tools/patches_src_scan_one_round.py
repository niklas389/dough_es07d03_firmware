"""Source of patches/scan-one-round.json. Run in an unpacked work dir (RT=runtime_0x200000.bin).

Automatic input: one scan round instead of two before "No signal".

The scan handler sub_25FE39 counts no-signal decisions in 0x453BF2 (cleared
only when a port finds a signal). While the count is <= the limit it steps to
the next input; above it, it shows "No signal". The limit is 8 normally and 4
in the factory mode (0x4551AE bit 0 or settings +0x48 bit 2):
  0x26002B sfeqi r6,0 ; 0x26002E cmovii r6,8,4   (r6 = flag clear ? 8 : 4)
So after a lost picture the stock scan visits all four inputs twice (9th
decision -> "No signal"). Patch: the normal limit 8 -> 4, as the factory mode:
one round, the 5th decision (back on the input that was lost) shows
"No signal" (docs/firmware-map.md section 59). With scan-active-first v2 the
search usually ends earlier (no input left that can have a source); this
limit is the upper bound.
"""
import sys, json, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'aeon'))
import aeondis as A, aeonasm as S

d = open(os.environ.get('RT', 'runtime_0x200000.bin'), 'rb').read()
def cur(a, n): return d[a - 0x200000:a - 0x200000 + n]

SITE = 0x26002E
x = A.decode(d, SITE - 0x200000, SITE)
assert x['name'] == 'bn.cmovii' and x['ops'] == 'r6,0x8,0x4', x
assert A.decode(d, 0x26002B - 0x200000, 0x26002B)['ops'] == 'r6,0x0'                 # sfeqi r6,0
assert A.decode(d, 0x26003C - 0x200000, 0x26003C)['ops'].startswith('r7,r6,')        # bleu r7,r6 (count <= limit: step)
new = S.encode('bn.cmovii', {'D': 6, 'I': 4, 'L': 4}, SITE)
assert len(new) == 3 and A.decode(new, 0, SITE)['ops'] == 'r6,0x4,0x4'
patch = {
 'name': 'scan-one-round',
 'summary': 'Automatic input: "No signal" after one scan round over the inputs instead of two (vendor factory-mode limit 4 instead of 8 no-signal decisions)',
 'status': 'untested (emulator-checked)',
 'edits': [{'addr': '0x%06X' % SITE, 'old': cur(SITE, 3).hex(), 'new': new.hex(),
            'asm': 'sub_25FE39: scan limit cmovii r6,8,4 -> cmovii r6,4,4 (one round in normal mode, as in the factory mode)'}],
 'notes': 'See the docstring of tools/patches_src_scan_one_round.py. Generated by tools/patches_src_scan_one_round.py.',
}
out = os.environ.get('OUT', 'scan-one-round.json')
json.dump(patch, open(out, 'w'), indent=2)
open(out, 'a').write('\n')
print('%06x: %s -> %s' % (SITE, cur(SITE, 3).hex(), new.hex()))
