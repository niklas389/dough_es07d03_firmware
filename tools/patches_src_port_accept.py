"""Source of patches/port-accept.json. Run in an unpacked work dir (RT=runtime_0x200000.bin).

Shorter signal-acceptance time for the input ports of type 0x20 (ports 0
and 1 of the port table 0x3B4950; port 1 is the DP input in use).

Vendor mechanism (identical structure in the LG 28MQ780 image, same SDK):
- sub_22F2C7 runs the port monitor sub_23B068 for each port every 20 ms (per-port
  countdown at +0x14: reloaded with 20, reduced by 10 per 10 ms tick).
- sub_23B068 counts +0x16 up by one per pass while the port shows a stable
  signal (a timing change found by sub_23A7CB sends the port back to
  state 1). At +0x18 passes the signal is accepted (sub_23E64A(port, 3): port state 3); at +0x1A passes
  without a signal the port is declared "no signal" (state 2).
- sub_260E0E sets +0x18 / +0x1A per port type (word +4) via sub_23E5C5.
  Type 0x20 (no bit 0-4, no 0x400): 80 / 400 passes (1.6 s / 8 s), or
  50 / 200 when settings +0x48 bit 2 or flg (0x4551AE) bit 0 is set (bit 0 is
  set only when the EEPROM magic is missing).
- Measured (2026-10-07): port 1 accepted 1.60 s after its status showed a
  signal, in two runs = 80 passes.
- LG 28MQ780 (sub_25E480, same table layout with 0xB8-byte entries): type 0x20
  30 / 100 passes, type 0x08/0x10/0x400 20 / 100, bits 1/2 20 / 20, bit 0 10 / 20.

Patch: the 80-pass accept threshold for type 0x20 becomes ACCEPT passes
(env ACCEPT, default 30 = 0.6 s, the LG value). The no-signal threshold and
the other port types are unchanged.
"""
import sys, json, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'aeon'))
import aeondis as A, aeonasm as S

d = open(os.environ.get('RT', 'runtime_0x200000.bin'), 'rb').read()
def cur(a, n): return d[a - 0x200000:a - 0x200000 + n]

ACCEPT = int(os.environ.get('ACCEPT', '30'))
assert 10 <= ACCEPT <= 80
ADDR = 0x260EDE                     # sub_260E0E: ori r4,r0,0x50 (type 0x20 accept threshold, normal case)
assert cur(ADDR, 3).hex() == '508050', cur(ADDR, 3).hex()
x = A.decode(d, ADDR - 0x200000, ADDR)
assert x['mnem'] == 'b.ori' and x['ops'] == 'r4,r0,0x50', x
new = S.encode('bn.ori', {'D': 4, 'A': 0, 'N': ACCEPT}, ADDR)
assert len(new) == 3 and A.decode(new, 0, ADDR)['ops'] == 'r4,r0,%#x' % ACCEPT, new.hex()
print('%06x: %s -> %s  (%s)' % (ADDR, cur(ADDR, 3).hex(), new.hex(), A.decode(new, 0, ADDR)['ops']))
patch = {
 'name': 'port-accept',
 'summary': 'Accept a stable signal on input ports 0 and 1 (type 0x20; port 1 = DP input) after %d x 20 ms = %.1f s instead of 1.6 s'
            % (ACCEPT, ACCEPT * 0.02),
 'status': 'hardware-tested 2026-10-07: deep-standby wakes, power-key and mains starts without issues',
 'edits': [
  {'addr': '0x%06X' % ADDR, 'old': cur(ADDR, 3).hex(), 'new': new.hex(),
   'asm': 'sub_260E0E ori r4,r0,0x50 -> ori r4,r0,%#x (port +0x18 accept threshold for type 0x20)' % ACCEPT},
 ],
 'notes': ("Port monitor sub_23B068 runs every 20 ms per port and accepts the signal after +0x18 stable passes "
           "(vendor 80 = 1.6 s for type 0x20). LG 28MQ780 firmware (same SDK) uses 30. A timing change "
           "during the window still sends the port back to state 1 (sub_23A7CB). No-signal threshold (400 passes) and "
           "other port types unchanged. Generated by tools/patches_src_port_accept.py (ACCEPT=n, 10-80)."),
}
out = os.environ.get('OUT', 'port-accept.json')
json.dump(patch, open(out, 'w'), indent=2)
open(out, 'a').write('\n')
