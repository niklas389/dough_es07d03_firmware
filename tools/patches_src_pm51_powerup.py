"""Source of patches/pm51-powerup.json. Run in an unpacked work dir (PM=pm51_0x10080.bin).

PM51 standby controller, wake from deep standby: the settle time after the
power-good poll becomes 50 ms instead of 100 ms.

Wake power-up in the PM51 power state machine (0x3EB4, block 0x4070-0x40BE,
docs/firmware-map.md section 25): reg 0x36, 5 ms (0x4078), reg 0x36 again,
reg 0x34, poll reg 0x9C bit 1 every pass for up to 1000 (0x5E59 = 0x3E8),
then a fixed wait of 100 ms (0x40B7 mov r7,#0x64; mov r6,#0; lcall 0x9D1F
= delay in ms) before the main CPU is started.
GP27U (0x5517) and M27P20P (0x511C), the latter with the same MST9U + MSB3300
combination, wait 50 ms (mov r7,#0x32) after the same poll. Their sequence
before the poll differs from ours (one reg 0x36 write, no 5 ms wait), so only
the settle time after the poll is changed here; the 5 ms between our two
reg 0x36 writes stays.
Saves 50 ms per deep-standby wake.
"""
import json, os

d = open(os.environ.get('PM', 'pm51_0x10080.bin'), 'rb').read()
def cur(a, n): return d[a:a + n]

SITE = 0x40B7
assert cur(SITE, 7).hex() == '7f647e00129d1f'                 # mov r7,#100 ; mov r6,#0 ; lcall 0x9D1F
assert cur(0x40A1, 2).hex() == '7f9c'                         # the reg 0x9C power-good poll before it
assert cur(0x40AA, 3).hex() == '20e10a'                       # jb acc.1,0x40B7 (poll done)
assert cur(0x4078, 7).hex() == '7f057e00129d1f'               # the 5 ms wait (kept)
MS = int(os.environ.get('SETTLE_MS', '50'))
assert 50 <= MS <= 100
new = bytes([0x7F, MS])

patch = {
 'name': 'pm51-powerup',
 'summary': 'PM51 deep-standby wake: settle time after the power-good poll %d ms instead of 100 ms (GP27U / M27P20P: 50 ms)' % MS,
 'status': 'on hold: left out of builds since 2026-10-08 until the hang of docs/firmware-map.md section 39 is explained',
 'space': 'pm51',
 'edits': [
  {'addr': '0x%04X' % SITE, 'old': cur(SITE, 2).hex(), 'new': new.hex(),
   'asm': 'power state machine wake power-up: mov r7,#0x64 -> mov r7,#%#04x (delay in ms after the reg 0x9C poll)' % MS},
 ],
 'notes': ('Addresses are PM51 code addresses (package offset 0x10080 + addr). The 5 ms wait at 0x4078 and the '
           'power-good poll are unchanged. Generated by tools/patches_src_pm51_powerup.py (SETTLE_MS=50-100).'),
}
out = os.environ.get('OUT', 'pm51-powerup.json')
json.dump(patch, open(out, 'w'), indent=2)
open(out, 'a').write('\n')
print(patch['edits'])
