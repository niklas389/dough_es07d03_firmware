"""Source of patches/bl-supply-off.json. Run in an unpacked work dir (RT=runtime_0x200000.bin).

Switch the backlight supply off together with the panel, so the LEDs do not
glow in link-held standby.

The vendor panel-off (sub_245860) only drops the backlight enable 0x426 bit 6.
The LED supply stays on, and enough of it reaches the LED strings for a faint
glow. Its switch is pin 0x44B bit 3 (driven, 0x44D bit 3 = 0): power_event
sets it at power-on (0x260F67), the PM51 on wake, and the vendor clears it only
on the way into deep standby / power-off (0x23D72F, 0x261062).

- sub_245860 (panel off, after VLCD off, at its epilogue 0x24590C): clear
  0x44B bit 3. Not reached when the panel was already off (pnl guard).
- sub_245919 (panel on, at its entry 0x245919): set 0x44B bit 3. The
  backlight enable follows only after VLCD, eDP, link training and 550 ms.

Hardware (2026-10-04): clearing the bit removes the glow with CPU, DDC and DP
link running; setting it again plus a vendor panel-on lights the backlight.
Setting it again plus only the enable pin did not. With the patch: 0x44B reads
0x02 in link-held standby and the backlight comes back on wake, without a
firmware restart (diag-poke marker kept).

Requires standby-lhs: the stock pre-standby cancel sub_2457FB switches the
backlight on without going through sub_245919.
"""
import sys, json, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'aeon'))
import aeondis as A, aeonasm as S

d = open(os.environ.get('RT', 'runtime_0x200000.bin'), 'rb').read()
def cur(a, n): return d[a - 0x200000:a - 0x200000 + n]

CAVE = 0x203940                     # after panel-t12 (0x203900-0x203931)
REG_WRITE_MASK = 0x23DADB           # (reg, set?, mask) under the PM51 register lock
OFF_HOOK, ON_HOOK = 0x24590C, 0x245919
ON_CONT = 0x24591E                  # sub_245919: sw 0(r1),r10
R1, R3, R4, R5, R9 = 1, 3, 4, 5, 9
ori = lambda rd, v: ('bg.ori', {'D': rd, 'A': 0, 't': v})

prog = [
 'off_tail:',                       # replaces sub_245860 epilogue: lwz r9,0(r1); addi r1,4; jr r9
 ori(R3, 0x44B), ('bt.movi', {'D': R4, 'I': 0}), ('bt.movi', {'D': R5, 'I': 8}),
 ('bg.jal', {'/': REG_WRITE_MASK}),
 ('bn.lwz', {'D': R9, 'A': R1, ':': 0}), ('bt.addi', {'D': R1, 'I': 4}), ('bt.jr', {'A': R9}),
 'on_entry:',                       # replaces sub_245919 prologue: addi r1,-8; sw 4(r1),r9
 ('bt.addi', {'D': R1, 'I': -8}), ('bn.sw', {':': 4, 'A': R1, 'B': R9}),
 ori(R3, 0x44B), ('bt.movi', {'D': R4, 'I': 1}), ('bt.movi', {'D': R5, 'I': 8}),
 ('bg.jal', {'/': REG_WRITE_MASK}),
 ('bg.j', {'/': ON_CONT}),
]
code, L = S.assemble(prog, CAVE)
for a, b, x in A.disasm(code, CAVE, CAVE + len(code), CAVE):
    lab = [k for k, v in L.items() if v == a]
    print(('%-10s' % (lab[0] + ':' if lab else '')) + '%08x: %-12s %-9s %s' % (a, b.hex(' '), x['mnem'], x['ops']))
assert CAVE + len(code) <= 0x203A00
assert cur(CAVE, len(code)) == b'\0' * len(code)
assert cur(OFF_HOOK, 7).hex() == '0d21029c248529', cur(OFF_HOOK, 7).hex()   # lwz r9,0(r1); addi r1,4; jr r9
assert cur(ON_HOOK, 5).hex() == '9c380d2104', cur(ON_HOOK, 5).hex()         # addi r1,-8; sw 4(r1),r9
assert cur(ON_CONT, 3).hex() == '0d4100'                                      # sw 0(r1),r10

edits = [
 {'addr': '0x%06X' % CAVE, 'old': '00' * len(code), 'new': code.hex(),
  'asm': 'off_tail / on_entry (linker padding 0x203940): clear / set 0x44B bit 3 (backlight supply)'},
 {'addr': '0x%06X' % OFF_HOOK, 'old': cur(OFF_HOOK, 4).hex(), 'new': S.encode('bg.j', {'/': L['off_tail']}, OFF_HOOK).hex(),
  'asm': 'sub_245860 epilogue (lwz r9 + 1st byte of addi) -> j off_tail; the rest is never reached'},
 {'addr': '0x%06X' % ON_HOOK, 'old': cur(ON_HOOK, 4).hex(), 'new': S.encode('bg.j', {'/': L['on_entry']}, ON_HOOK).hex(),
  'asm': 'sub_245919 prologue (addi r1,-8 + 2 bytes of sw r9) -> j on_entry; continues at 0x24591E'},
]
out = os.environ.get('OUT', 'bl-supply-off.json')
if os.path.exists(out):
    patch = json.load(open(out)); patch['edits'] = edits
else:
    patch = {
     'name': 'bl-supply-off',
     'summary': 'Switch the backlight supply (0x44B bit 3) off with every panel-off and on at every panel-on; removes the standby glow',
     'status': 'experimental, hardware test pending',
     'requires': ['standby-lhs'],
     'edits': edits,
     'notes': ("The vendor panel-off only drops the backlight enable; the LED supply stays on and the LEDs glow faintly in "
               "link-held standby. 0x44B bit 3 switches that supply (the vendor clears it only for deep standby). "
               "Panel-off clears it after VLCD off; panel-on sets it before VLCD on, about 600 ms before the backlight enable. "
               "Generated by tools/patches_src_bl_supply.py."),
    }
json.dump(patch, open(out, 'w'), indent=2)
open(out, 'a').write('\n')
