#!/usr/bin/env python3
"""Source of patches/audio-off.json and patches/eeprom-fast-read.json.
Run in an unpacked work dir (RT=runtime_0x200000.bin, OUTDIR=patches dir).

audio-off: sub_20C579 powers up the NAU8401 headphone DAC (I2C 0x34) with the
datasheet's anti-pop procedure (R1=0x10F, wait 250 ms, register table, wait
100 ms) on every start and wake. The patch jumps from its first delay call
straight to the trailing pin writes (0x44B/0x44D bit 7), inside the same stack
frame. The DAC stays in its power-on reset state (outputs off).

eeprom-fast-read: the bit-banged I2C read-bit routine sub_240134 (used only for
EEPROM reads) waits 4 us per half clock (sub_241702). Its four delay calls go
to a 2 us variant instead (~200 kHz; FM24C128D is rated 1 MHz at 2.5-5.5 V).
Writes keep the stock timing.
"""
import sys, json, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'aeon'))
import aeondis as A, aeonasm as S

d = open(os.environ.get('RT', 'runtime_0x200000.bin'), 'rb').read()
outdir = os.environ.get('OUTDIR', '.')
def cur(a, n): return d[a - 0x200000:a - 0x200000 + n]

def edit(a, old, op, target, why):
    ob = cur(a, 4)
    assert ob.hex() == old, (hex(a), ob.hex())
    nb = S.encode(op, {'/': target}, a)
    x, y = A.decode(ob, 0, a), A.decode(nb, 0, a)
    print('%x  %s %-22s -> %s %s' % (a, ob.hex(), x['mnem'] + ' ' + x['ops'], nb.hex(), y['mnem'] + ' ' + y['ops']))
    return {'addr': '0x%06X' % a, 'old': ob.hex(), 'new': nb.hex(),
            'asm': '%s %s -> %s %s (%s)' % (x['mnem'], x['ops'], y['mnem'], y['ops'], why)}

def save(p):
    path = os.path.join(outdir, p['name'] + '.json')
    json.dump(p, open(path, 'w'), indent=2)
    open(path, 'a').write('\n')

# --- audio-off ---------------------------------------------------------------
assert cur(0x20C5CC, 4).hex() == 'c860044b'          # ori r3,r0,0x44b (pin writes)
save({
 'name': 'audio-off',
 'summary': 'Skip the headphone DAC (NAU8401) power-up at start and wake: saves ~350 ms of anti-pop waits; the 3.5 mm output stays off',
 'status': 'experimental, hardware test pending',
 'edits': [edit(0x20C580, 'e4069f0a', 'bg.j', 0x20C5CC,
                'sub_20C579: skip NAU8401 reset/power-up writes and the 1+1+250+100 ms waits, keep the 0x44B/0x44D bit 7 pin writes')],
 'notes': ("I2C 0x34 is the NAU8401 DAC (datasheet: fixed device address 0011010). sub_20C579 runs the datasheet's anti-pop "
           "power-up (R1 = 0x10F, ~250 ms, configuration table at 0x34220B, 100 ms) on every start and wake from standby. "
           "No other code writes the DAC except the standby-entry sequence sub_20C537. With the patch the DAC keeps its "
           "power-on reset state (all outputs disabled), so the headphone output is silent. "
           "Generated by tools/patches_src_audio_eeprom.py."),
})

# --- eeprom-fast-read ----------------------------------------------------------
CAVE = 0x203B00
code, L = S.assemble(['delay2:', ('bt.movi', {'D': 3, 'I': 2}), ('bg.j', {'/': 0x20E375})], CAVE)
for a, b, x in A.disasm(code, CAVE, CAVE + len(code), CAVE):
    print('%08x: %-12s %-9s %s' % (a, b.hex(' '), x['mnem'], x['ops']))
assert cur(CAVE, len(code)) == b'\0' * len(code)
assert cur(0x241702, 6).hex() == '9864e7f998e3'       # stock: movi r3,4; j 0x20e375
edits = [{'addr': '0x%06X' % CAVE, 'old': '00' * len(code), 'new': code.hex(),
          'asm': 'delay2: b.movi r3,2; b.j 0x20e375 (delay_us)'}]
for a, old in [(0x240163, 'e4002b3e'), (0x240174, 'e4002b1c'), (0x2401CD, 'e4002a6a'), (0x2401DE, 'e4002a48')]:
    edits.append(edit(a, old, 'bg.jal', L['delay2'], 'sub_240134 (EEPROM read bit/ACK): 4 us -> 2 us half-period delay'))
save({
 'name': 'eeprom-fast-read',
 'summary': 'Read the settings EEPROM with 2 us instead of 4 us clock half-periods (~200 kHz; FM24C128D is rated 1 MHz); writes unchanged',
 'status': 'tested, does not work: after power-key off/on the monitor shows No signal and returns to standby (bisected 2026-10-04); kept for reference',
 'edits': edits,
 'notes': ("sub_240134 is the bit-banged I2C read-bit routine and is only reached from the EEPROM block read (sub_2403B5). "
           "Worst case if the EEPROM misread: settings reload to defaults (user area only); the factory area 0x1794-0x1C2F is "
           "never written by normal code and a checksum failure there only loads defaults into RAM. "
           "Generated by tools/patches_src_audio_eeprom.py."),
})
