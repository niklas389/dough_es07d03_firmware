#!/usr/bin/env python3
"""Source of patches/standby-timeout.json. Run in an unpacked work dir (RT=runtime_0x200000.bin).

Shorter "No signal" -> power-save countdown.

Vendor: the OSD state 4 entry handler sub_26A7C5 sets the countdown cnt
(0x4551A6) to 255 (0x26A7D5 movi r7,-1; sb 0x51a6(r10),r7). The countdown
task sub_261C04 enters pre-standby (dark, red LED) when cnt == 250
(0x261CE4 sfnei r6,0xfa) and requests power-save at 0. So the panel goes
dark after 5 s and deep standby follows ~250 s later.

Patch: start value SECONDS (env STANDBY_S, default 30), pre-standby still 5 s
after "No signal" (compare value SECONDS - 5). The other countdown users are
unchanged (state 3 "cable not connected" 10 s, sub_26A7A9 5 s, the 1-tick
path for flg bit 0 at 0x26A7ED).
"""
import sys, json, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'aeon'))
import aeondis as A, aeonasm as S

d = open(os.environ.get('RT', 'runtime_0x200000.bin'), 'rb').read()
def cur(a, n): return d[a - 0x200000:a - 0x200000 + n]

SECONDS = int(os.environ.get('STANDBY_S', '30'))
assert 10 <= SECONDS <= 255
CAVE = 0x203932                     # after panel-t12 (0x203900-0x203931), before bl-supply-off (0x203940)
HOOK = 0x26A7D5                     # movi r7,-1 ; sb 0x51a6(r10),r7
CMP = 0x261CE4                      # sfnei r6,0xfa (pre-standby at cnt == 250)
R0, R7, R10 = 0, 7, 10

prog = [
 'sto:',
 ('bn.ori', {'D': R7, 'A': R0, 'N': SECONDS}), ('bg.sb', {'Y': 0x51A6, 'A': R10, 'B': R7}),
 ('bg.j', {'/': 0x26A7DB}),
]
code, L = S.assemble(prog, CAVE)
for a, b, x in A.disasm(code, CAVE, CAVE + len(code), CAVE):
    print('%08x: %-12s %-9s %s' % (a, b.hex(' '), x['mnem'], x['ops']))
assert CAVE + len(code) <= 0x203940
assert cur(CAVE, len(code)) == b'\0' * len(code)
assert cur(HOOK, 6).hex() == '98fff8ea51a6', cur(HOOK, 6).hex()
assert cur(CMP, 4).hex() == 'c0c01f44', cur(CMP, 4).hex()
new_cmp = S.encode('bg.sfnei', {'A': 6, 'Y': SECONDS - 5}, CMP)
assert A.decode(cur(CMP, 4), 0, CMP)['mnem'] == A.decode(new_cmp, 0, CMP)['mnem']
patch = {
 'name': 'standby-timeout',
 'summary': '"No signal" -> power-save after %d s instead of 255 s (panel still dark after 5 s)' % SECONDS,
 'status': 'hardware-tested 2026-10-07 (30 s: link-held or deep standby about 30 s after the source stops)',
 'edits': [
  {'addr': '0x%06X' % CAVE, 'old': '00' * len(code), 'new': code.hex(),
   'asm': 'standby-timeout: cnt = %d (linker padding 0x203932)' % SECONDS},
  {'addr': '0x%06X' % HOOK, 'old': cur(HOOK, 4).hex(), 'new': S.encode('bg.j', {'/': L['sto']}, HOOK).hex(),
   'asm': 'sub_26A7C5 movi r7,-1 + first half of sb 0x51a6(r10),r7 -> j sto (0x26A7D9-0x26A7DA unused)'},
  {'addr': '0x%06X' % CMP, 'old': cur(CMP, 4).hex(), 'new': new_cmp.hex(),
   'asm': 'sub_261C04 sfnei r6,0xfa -> sfnei r6,%d (pre-standby 5 s after "No signal")' % (SECONDS - 5)},
 ],
 'notes': ("State 4 ('No signal') entry sets the countdown to %d s; pre-standby (panel and backlight off, red LED) "
           "still starts 5 s after the message, power-save is requested at 0 (deep standby, or link-held standby "
           "when the source holds the link). Vendor: 255 s. Generated by tools/patches_src_standby_timeout.py "
           "(STANDBY_S=n for another value, 10-255)." % SECONDS),
}
out = os.environ.get('OUT', 'standby-timeout.json')
json.dump(patch, open(out, 'w'), indent=2)
open(out, 'a').write('\n')
