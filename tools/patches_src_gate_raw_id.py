"""Source of patches/gate-raw-id.json. Run in an unpacked work dir (RT=runtime_0x200000.bin).

Standby gate: ask the front-end about the current DP-class connector by its
own id, without the 0x30/7 mapping.

Vendor gate sub_2612F9 (docs/firmware-map.md sections 24, 29): for a current
port of the DP class it takes the connector code 0x3B427B[port] (USB-C 8,
DP 7), maps it with 0x30 sub 7 (sub_23956D) and sends the result to 0x60
sub 0xB. Answer 0 = a source is active -> standby refused; 1 = no source.

Problem (2026-10-08): after USB-C was unplugged, 0x30/7 answered 0 ("no
index") for the USB-C code, while the raw query for USB-C's id 7 answered 1
(no source). 0x60/0xB with index 0 answers 0, which the gate reads as "source
active", so with USB-C as the current port standby is refused for good (with
standby-lhs: link-held standby that never ends). sub_23956D also returns 0 when
the mailbox transaction fails, with the same result. Earlier runs showed that
the 0x30/7 answer follows the front-end's current routing rather than the code,
so the vendor gate asks about the routed connector, not necessarily the
current port's.

Patch (no code cave): the table the gate reads becomes 0x3B4281 (front-end ids:
port 0 USB-C 7, port 1 DP 8; the table sub_2394DC uses) instead of 0x3B427B
(codes), and the jal sub_23956D becomes a jump to the next instruction. The
gate then sends 0x60/0xB (id) for the current port's own connector - the
query diag-fe's raw mode ran on hardware - and saves one mailbox
transaction per gate query.
"""
import sys, json, os
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), 'aeon'))
import aeondis as A, aeonasm as S

d = open(os.environ.get('RT', 'runtime_0x200000.bin'), 'rb').read()
def cur(a, n): return d[a - 0x200000:a - 0x200000 + n]

assert cur(0x261330, 0x14).hex() == 'c0c00761fcc6427b8ca6106500e7fb0460186106', cur(0x261330, 0x14).hex()
assert A.decode(d, 0x26133D - 0x200000, 0x26133D)['target'] == 0x23956D
assert cur(0x3B427B, 2).hex() == '0807' and cur(0x3B4281, 2).hex() == '0708'   # codes / ids of ports 0, 1

addi = S.encode('bg.addi', {'D': 6, 'A': 6, 'Y': 0x4281}, 0x261334)
nojal = S.encode('bg.j', {'/': 0x261341}, 0x26133D)
for a, b in ((0x261334, addi), (0x26133D, nojal)):
    x = A.decode(b, 0, a)
    print('%06x: %s -> %s  %s %s' % (a, cur(a, 4).hex(), b.hex(), x['mnem'], x['ops']))

patch = {
 'name': 'gate-raw-id',
 'summary': ('Standby gate asks the front-end about the current DP / USB-C connector by its own id (0x60/0xB) '
             'instead of the 0x30/7 mapping, which answered "no index" for an unplugged USB-C and so refused standby'),
 'status': 'untested',
 'edits': [
  {'addr': '0x261334', 'old': cur(0x261334, 4).hex(), 'new': addi.hex(),
   'asm': 'sub_2612F9: addi r6,r6,0x427b (codes) -> 0x4281 (front-end ids)'},
  {'addr': '0x26133D', 'old': cur(0x26133D, 4).hex(), 'new': nojal.hex(),
   'asm': 'sub_2612F9: jal sub_23956D (0x30/7 mapping) -> j 0x261341 (r3 = id)'},
 ],
 'notes': 'See the docstring of tools/patches_src_gate_raw_id.py. Generated by tools/patches_src_gate_raw_id.py.',
}
out = os.environ.get('OUT', 'gate-raw-id.json')
json.dump(patch, open(out, 'w'), indent=2)
open(out, 'a').write('\n')
